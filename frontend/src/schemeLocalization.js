// LOCALIZATION HELPERS
// ============================================================================

/**
 * Get localized ministry/department name
 * @param {string} dept - Department name in English
 * @param {string} lang - Language code ('en' or 'ta')
 * @returns {string} Localized department name (fallback to English)
 */
export function getLocalizedDepartment(dept, lang = 'en') {
  if (!dept || lang === 'en') return dept;
  return MINISTRY_TRANSLATIONS[dept]?.ta || dept;
}

/**
 * Get localized document name
 * @param {string} doc - Document name in English
 * @param {string} lang - Language code ('en' or 'ta')
 * @returns {string} Localized document name (fallback to English)
 */
export function getLocalizedDocument(doc, lang = 'en') {
  if (!doc || lang === 'en') return doc;
  return DOCUMENT_TRANSLATIONS[doc]?.ta || doc;
}

/**
 * Get localized documents array
 * @param {string[]} docs - Array of document names in English
 * @param {string} lang - Language code ('en' or 'ta')
 * @returns {string[]} Array of localized document names
 */
export function getLocalizedDocuments(docs, lang = 'en') {
  if (!Array.isArray(docs) || lang === 'en') return docs;
  return docs.map(doc => getLocalizedDocument(doc, lang));
}

/**
 * Get localized benefit text
 * Preserves numerical values and currency symbols while translating surrounding text
 * @param {string} benefit - Benefit text in English
 * @param {string} lang - Language code ('en' or 'ta')
 * @returns {string} Localized benefit text
 */
export function getLocalizedBenefit(benefit, lang = 'en') {
  if (!benefit || lang === 'en') return benefit;

  // If scheme has benefit_ta, use it directly
  // Otherwise fallback to English
  return benefit;
}

/**
 * Get comprehensive localized scheme content
 * @param {object} scheme - Scheme object with English and optional Tamil fields
 * @param {string} lang - Language code ('en' or 'ta')
 * @returns {object} Scheme with localized content
 */
export function getLocalizedScheme(scheme, lang = 'en') {
  if (!scheme) return null;
  if (lang === 'en') return scheme;

  return {
    ...scheme,
    // Official scheme name stays in English unless explicitly provided
    name: scheme.name_ta || scheme.name,
    // Department localization
    department: getLocalizedDepartment(scheme.department, lang),
    // Description localization
    description: scheme.description_ta || scheme.description,
    // Benefits localization
    benefits: scheme.benefits_ta || scheme.benefits,
    // Documents localization
    documents: getLocalizedDocuments(scheme.documents, lang),
    // Application method localization
    applicationMethod: scheme.applicationMethod_ta || scheme.applicationMethod,
  };
}

