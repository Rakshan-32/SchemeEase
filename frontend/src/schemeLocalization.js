export function getLocalizedApplicationMethod(scheme, lang = 'en') {
  if (!scheme || lang === 'en') return scheme.applicationMethod;
  return scheme.applicationMethod_ta || scheme.applicationMethod;
}

/**
 * Validate that a scheme has all required English fields
 * @param {object} scheme - Scheme object
 * @returns {object} Validation result with missing fields
 */
export function validateSchemeStructure(scheme) {
  const required = ['id', 'name', 'category', 'department', 'description', 'benefits', 'documents', 'applicationMethod'];
  const missing = required.filter(field => !scheme[field]);

  return {
    valid: missing.length === 0,
    missing,
  };
}

/**
 * Get Tamil localization coverage for a scheme
 * @param {object} scheme - Scheme object
 * @returns {object} Coverage statistics
 */
export function getTamilCoverage(scheme) {
  if (!scheme) return { total: 0, covered: 0, percentage: 0 };

  const fields = ['name_ta', 'description_ta', 'benefits_ta', 'applicationMethod_ta'];
  const covered = fields.filter(field => scheme[field]).length;

  return {
    total: fields.length,
    covered,
    percentage: Math.round((covered / fields.length) * 100),
    missing: fields.filter(field => !scheme[field]).map(f => f.replace('_ta', '')),
  };
}
